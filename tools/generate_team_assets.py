"""Convert Teams SVGs at native size, reusing identical existing LVGL assets."""
from hashlib import sha256
from io import BytesIO
from math import ceil
from pathlib import Path
import xml.etree.ElementTree as ET

from PIL import Image
import resvg_py

ROOT = Path(__file__).resolve().parents[1]


def render(source):
    root = ET.parse(source).getroot()
    size = tuple(ceil(float(root.attrib[k].replace("px", ""))) for k in ("width", "height"))
    png = resvg_py.svg_to_bytes(svg_path=str(source), zoom=4, skip_system_fonts=True)
    image = Image.open(BytesIO(png)).convert("RGBA").resize(size, Image.Resampling.LANCZOS)
    # Match the transforms of the native SVG instances in Figma. Originals stay intact.
    if source.stem in ("view3_imgGroup", "view3_imgGroup1", "view3_imgGroup2"):
        image = image.transpose(Image.Transpose.ROTATE_180)
    if source.stem == "view4_imgVector":
        image = image.transpose(Image.Transpose.FLIP_TOP_BOTTOM)
    assert image.getbbox() is not None, source
    raw = image.tobytes("raw", "BGRA")
    return size, raw, (size, sha256(raw).hexdigest())


def main():
    known = {}
    for directory, prefix in (("quick_task", "havit_quick_task_"), ("today", "havit_")):
        for source in sorted((ROOT / "ui/assets" / directory).glob("*.svg")):
            size, raw, digest = render(source)
            known[digest] = prefix + source.stem
    definitions = ['/* Generated by tools/generate_team_assets.py. */', '#include "lvgl.h"']
    declarations = ['#pragma once', '#include "havit_quick_task_assets.h"', '#include "havit_today_assets.h"']
    for source in sorted((ROOT / "ui/assets/team").glob("*.svg")):
        (width, height), raw, digest = render(source)
        name = "havit_team_" + source.stem
        if digest in known:
            declarations.append(f"#define {name} {known[digest]}")
            print(f"{source.stem}: reuse {known[digest]} ({width}x{height})")
            continue
        known[digest] = name
        declarations.append(f"extern const lv_image_dsc_t {name};")
        definitions.append(f"static const uint8_t {name}_pixels[] = {{")
        for offset in range(0, len(raw), 24):
            definitions.append("    " + ",".join(f"0x{v:02x}" for v in raw[offset:offset+24]) + ",")
        definitions.extend(["};", f"const lv_image_dsc_t {name} = {{",
            "    .header.magic = LV_IMAGE_HEADER_MAGIC,",
            "    .header.cf = LV_COLOR_FORMAT_ARGB8888,",
            f"    .header.w = {width}, .header.h = {height}, .header.stride = {width * 4},",
            f"    .data_size = sizeof({name}_pixels), .data = {name}_pixels,", "};"])
        print(f"{source.stem}: new asset ({width}x{height})")
    (ROOT / "ui/assets/team_assets.c").write_text("\n".join(definitions) + "\n", encoding="utf-8")
    (ROOT / "ui/include/havit_team_assets.h").write_text("\n".join(declarations) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
