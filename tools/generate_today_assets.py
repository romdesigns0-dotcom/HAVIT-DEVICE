"""Rasterize local Figma SVG assets offline; firmware uses native LVGL images.

Requires Pillow and resvg-py. Run from the repository root. Identical raster
assets are emitted once, and the header aliases their design-specific names.
"""
from pathlib import Path
import hashlib
import math
import xml.etree.ElementTree as ET
from io import BytesIO
import resvg_py
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'ui/assets/today'
OUTPUT = ROOT / 'ui/assets/today_assets.c'
HEADER = ROOT / 'ui/include/havit_today_assets.h'

def main():
    definitions = ['/* Generated by tools/generate_today_assets.py. */', '#include "lvgl.h"']
    declarations = ['#pragma once', '#include "lvgl.h"']
    seen = {}
    for source in sorted(ASSETS.glob('*.svg')):
        svg = ET.parse(source).getroot()
        width = math.ceil(float(svg.attrib['width'].replace('px', '')))
        height = math.ceil(float(svg.attrib['height'].replace('px', '')))
        png = resvg_py.svg_to_bytes(svg_path=str(source), zoom=4,
                                   skip_system_fonts=True)
        image = Image.open(BytesIO(png)).convert('RGBA')
        image = image.resize((width, height), Image.Resampling.LANCZOS)
        if image.getbbox() is None:
            raise ValueError(f'Empty rendered asset: {source.name}')
        raw = image.tobytes('raw', 'BGRA')
        name = 'havit_' + source.stem
        digest = hashlib.sha256(raw).hexdigest()
        if digest in seen:
            declarations.append(f'#define {name} {seen[digest]}')
            continue
        seen[digest] = name
        declarations.append(f'extern const lv_image_dsc_t {name};')
        definitions.append(f'static const uint8_t {name}_pixels[] = {{')
        for offset in range(0, len(raw), 24):
            definitions.append('    ' + ','.join(f'0x{v:02x}' for v in raw[offset:offset+24]) + ',')
        definitions.extend(['};', f'const lv_image_dsc_t {name} = {{',
            '    .header.magic = LV_IMAGE_HEADER_MAGIC,',
            '    .header.cf = LV_COLOR_FORMAT_ARGB8888,',
            f'    .header.w = {width}, .header.h = {height}, .header.stride = {width * 4},',
            f'    .data_size = sizeof({name}_pixels), .data = {name}_pixels,', '};'])
    OUTPUT.write_text('\n'.join(definitions) + '\n', encoding='utf-8')
    HEADER.write_text('\n'.join(declarations) + '\n', encoding='utf-8')
    print(f'{len(seen)} unique rasters from {len(list(ASSETS.glob("*.svg")))} design assets')

if __name__ == '__main__':
    main()
