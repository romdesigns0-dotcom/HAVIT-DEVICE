"""Generate compact, native LVGL image descriptors from the Hoy task SVGs."""
from pathlib import Path
from io import BytesIO
import xml.etree.ElementTree as ET
import resvg_py
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "ui/assets/today_tasks"
OUT = ROOT / "ui/assets/today_task_assets.c"
HEADER = ROOT / "ui/include/havit_today_task_assets.h"

def main():
    c = ['/* Generated by tools/generate_today_task_assets.py. */', '#include "lvgl.h"']
    h = ['#pragma once', '#include "lvgl.h"']
    for path in sorted(ASSETS.glob("*.svg")):
        root = ET.parse(path).getroot()
        w = round(float(root.attrib["width"].replace("px", "")))
        height = round(float(root.attrib["height"].replace("px", "")))
        png = resvg_py.svg_to_bytes(svg_path=str(path), zoom=4, skip_system_fonts=True)
        image = Image.open(BytesIO(png)).convert("RGBA").resize((w, height), Image.Resampling.LANCZOS)
        raw = image.tobytes("raw", "BGRA")
        name = "havit_" + path.stem
        h.append(f"extern const lv_image_dsc_t {name};")
        c.append(f"static const uint8_t {name}_pixels[] = {{")
        for i in range(0, len(raw), 24):
            c.append("    " + ",".join(f"0x{x:02x}" for x in raw[i:i+24]) + ",")
        c += ["};", f"const lv_image_dsc_t {name} = {{",
              "    .header.magic = LV_IMAGE_HEADER_MAGIC,",
              "    .header.cf = LV_COLOR_FORMAT_ARGB8888,",
              f"    .header.w = {w}, .header.h = {height}, .header.stride = {w * 4},",
              f"    .data_size = sizeof({name}_pixels), .data = {name}_pixels,", "};"]
    OUT.write_text("\n".join(c) + "\n", encoding="utf-8")
    HEADER.write_text("\n".join(h) + "\n", encoding="utf-8")
    print(f"Generated {len(list(ASSETS.glob('*.svg')))} LVGL assets")

if __name__ == "__main__":
    main()
