"""Rasterize the exact Quick Task SVGs from Figma as LVGL image assets.

Requires Pillow and resvg-py. Run from any directory with Python installed.
"""
from hashlib import sha256
from io import BytesIO
from math import ceil
from pathlib import Path
import xml.etree.ElementTree as ET

from PIL import Image
import resvg_py

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ui/assets/quick_task"
OUTPUT = ROOT / "ui/assets/quick_task_assets.c"
HEADER = ROOT / "ui/include/havit_quick_task_assets.h"


def svg_dimensions(svg: ET.Element) -> tuple[int, int]:
    view_box = svg.attrib.get("viewBox")
    width = svg.attrib.get("width")
    height = svg.attrib.get("height")
    if width and height:
        return ceil(float(width.replace("px", ""))), ceil(float(height.replace("px", "")))
    if view_box:
        _, _, box_width, box_height = (float(value) for value in view_box.split())
        return ceil(box_width), ceil(box_height)
    raise ValueError("SVG must have width/height or viewBox")


def main() -> None:
    definitions = ["/* Generated by tools/generate_quick_task_assets.py. */", '#include "lvgl.h"']
    declarations = ["#pragma once", '#include "lvgl.h"']
    emitted: dict[str, str] = {}

    for source in sorted(SOURCE.glob("*.svg")):
        root = ET.parse(source).getroot()
        width, height = svg_dimensions(root)
        png = resvg_py.svg_to_bytes(svg_path=str(source), zoom=4, skip_system_fonts=True)
        image = Image.open(BytesIO(png)).convert("RGBA")
        image = image.resize((width, height), Image.Resampling.LANCZOS)
        if image.getbbox() is None:
            raise ValueError(f"Empty rasterized asset: {source.name}")
        pixels = image.tobytes("raw", "BGRA")
        name = "havit_quick_task_" + source.stem
        digest = sha256(pixels).hexdigest()
        if digest in emitted:
            declarations.append(f"#define {name} {emitted[digest]}")
            continue

        emitted[digest] = name
        declarations.append(f"extern const lv_image_dsc_t {name};")
        definitions.append(f"static const uint8_t {name}_pixels[] = {{")
        for offset in range(0, len(pixels), 24):
            row = ",".join(f"0x{byte:02x}" for byte in pixels[offset:offset + 24])
            definitions.append(f"    {row},")
        definitions.extend([
            "};",
            f"const lv_image_dsc_t {name} = {{",
            "    .header.magic = LV_IMAGE_HEADER_MAGIC,",
            "    .header.cf = LV_COLOR_FORMAT_ARGB8888,",
            f"    .header.w = {width}, .header.h = {height}, .header.stride = {width * 4},",
            f"    .data_size = sizeof({name}_pixels), .data = {name}_pixels,",
            "};",
        ])

    OUTPUT.write_text("\n".join(definitions) + "\n", encoding="utf-8")
    HEADER.write_text("\n".join(declarations) + "\n", encoding="utf-8")
    print(f"{len(emitted)} unique Quick Task images from {len(list(SOURCE.glob('*.svg')))} SVGs")


if __name__ == "__main__":
    main()
